#!/usr/bin/env python3
"""Dong bo cau hinh AI: 1 ban goc .claude/ -> sinh ban cho Codex va Antigravity.

Ban goc (chi sua o day):
  CLAUDE.md                 huong dan chung cho Claude Code
  .claude/skills/<x>/       skill
  .claude/commands/**.md    lenh go /ten
  .claude/rules/**.md       luat luon bat
  .claude/agents/*.md       agent con (nhan vat chuyen gia)

Tu sinh (KHONG sua tay, chay lai script nay de cap nhat):
  AGENTS.md                       tu CLAUDE.md (Codex + Antigravity doc)
  .agents/skills/<x>/             copy nguyen tu .claude/skills/
  .agents/skills/<a-b>/SKILL.md   tu .claude/commands/a/b.md (lenh thanh skill)
  .agents/rules/<a-b>.md          tu .claude/rules/a/b.md, them trigger
  .codex/agents/<ten>.toml        tu .claude/agents/<ten>.md

Khong sinh ban sao: .claude/plans/ va .claude/references/ (tai lieu tra cuu,
cac cong cu doc thang tu .claude/ khi can).

Cach chay:  python scripts/sync-ai-config.py   (chay tu thu muc goc du an)
Chi dung thu vien chuan cua Python 3.
"""

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".claude"
CLAUDE_MD = ROOT / "CLAUDE.md"
AGENTS_MD = ROOT / "AGENTS.md"
AGENTS_DIR = ROOT / ".agents"
CODEX_AGENTS = ROOT / ".codex" / "agents"

HEADER = "<!-- GENERATED by scripts/sync-ai-config.py - DO NOT EDIT - sua ban goc trong .claude/ roi chay lai script -->"
FM_RE = re.compile(r"^---\n(.*?)\n---\n?", re.S)

# Rule kieu tai lieu lon, chi nap khi model thay can (trigger: model_decision).
# Rule khong nam trong tap nay mac dinh trigger: always_on.
MODEL_DECISION_RULES = set()


def split_frontmatter(text):
    m = FM_RE.match(text)
    if not m:
        return {}, text
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t", "-")):
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"').strip("'")
    return fm, text[m.end():]


def first_summary(body):
    for line in body.splitlines():
        s = line.strip()
        if s.startswith(">"):
            s = re.sub(r"^>\s*", "", s)
        if s and not s.startswith("#"):
            return s.strip("* ").strip()
    return ""


def toml_escape_multiline(text):
    # TOML basic multiline string: thoat dau \ va chuoi """ neu co
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def wipe_dir(path):
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def sync_root_guidance(report):
    if not CLAUDE_MD.exists():
        report.append("bo qua AGENTS.md: chua co CLAUDE.md")
        return
    if AGENTS_MD.exists() and "GENERATED by scripts/sync-ai-config.py" not in AGENTS_MD.read_text(encoding="utf-8"):
        report.append("giu nguyen AGENTS.md: file viet tay, khong de")
        return
    body = CLAUDE_MD.read_text(encoding="utf-8")
    AGENTS_MD.write_text(HEADER + "\n\n" + body, encoding="utf-8")
    report.append("AGENTS.md <- CLAUDE.md")


def sync_skills(report):
    dst_root = AGENTS_DIR / "skills"
    wipe_dir(dst_root)
    src_root = SRC / "skills"
    count = 0
    if src_root.exists():
        for item in sorted(src_root.iterdir()):
            if item.is_dir():
                shutil.copytree(item, dst_root / item.name)
                count += 1
    report.append(f".agents/skills/: copy {count} skill tu .claude/skills/")


def sync_commands_as_skills(report):
    src_root = SRC / "commands"
    dst_root = AGENTS_DIR / "skills"
    dst_root.mkdir(parents=True, exist_ok=True)
    count = 0
    if src_root.exists():
        for md in sorted(src_root.rglob("*.md")):
            rel = md.relative_to(src_root).with_suffix("")
            name = "-".join(rel.parts)
            fm, body = split_frontmatter(md.read_text(encoding="utf-8"))
            desc = fm.get("description") or first_summary(body) or f"Lenh /{name}"
            out_dir = dst_root / name
            out_dir.mkdir(parents=True, exist_ok=True)
            content = (
                f"---\nname: {name}\ndescription: {desc}\n---\n\n"
                + HEADER.replace("<!--", "<!-- nguon: .claude/commands/ -").rstrip("-->") + " -->\n\n"
                + body.lstrip()
            )
            (out_dir / "SKILL.md").write_text(content, encoding="utf-8")
            count += 1
    report.append(f".agents/skills/: sinh {count} skill tu .claude/commands/")


def sync_rules(report):
    dst_root = AGENTS_DIR / "rules"
    wipe_dir(dst_root)
    src_root = SRC / "rules"
    count = 0
    if src_root.exists():
        for md in sorted(src_root.rglob("*.md")):
            rel = md.relative_to(src_root).with_suffix("")
            flat = "-".join(rel.parts) + ".md"
            fm, body = split_frontmatter(md.read_text(encoding="utf-8"))
            trigger = fm.get("trigger")
            if not trigger:
                trigger = "model_decision" if flat in MODEL_DECISION_RULES else "always_on"
            head = f"---\ntrigger: {trigger}\n"
            for k, v in fm.items():
                if k != "trigger":
                    head += f"{k}: {v}\n"
            head += "---\n\n" + HEADER + "\n\n"
            (dst_root / flat).write_text(head + body.lstrip(), encoding="utf-8")
            count += 1
    report.append(f".agents/rules/: sinh {count} rule tu .claude/rules/")


def sync_codex_agents(report):
    wipe_dir(CODEX_AGENTS)
    src_root = SRC / "agents"
    count = 0
    if src_root.exists():
        for md in sorted(src_root.glob("*.md")):
            fm, body = split_frontmatter(md.read_text(encoding="utf-8"))
            name = fm.get("name") or md.stem
            desc = fm.get("description") or first_summary(body) or name
            toml = (
                f"# GENERATED by scripts/sync-ai-config.py - DO NOT EDIT - sua .claude/agents/{md.name}\n"
                f'name = "{name}"\n'
                f'description = "{desc}"\n'
                f'developer_instructions = """\n{toml_escape_multiline(body.strip())}\n"""\n'
            )
            (CODEX_AGENTS / f"{md.stem}.toml").write_text(toml, encoding="utf-8")
            count += 1
    report.append(f".codex/agents/: sinh {count} file TOML tu .claude/agents/")


def main():
    if not SRC.exists():
        print("Loi: khong thay thu muc .claude/ - chay script tu ban sao dat trong scripts/ cua du an.")
        return 1
    report = []
    sync_root_guidance(report)
    sync_skills(report)
    sync_commands_as_skills(report)
    sync_rules(report)
    sync_codex_agents(report)
    print("Da dong bo cau hinh AI:")
    for line in report:
        print(" -", line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
